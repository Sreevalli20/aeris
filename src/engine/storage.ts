export function loadProjectData(): AerisProjectData {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      saveProjectData(INITIAL_AERIS_DATA);
      return INITIAL_AERIS_DATA;
    }
    const parsed = JSON.parse(raw);
    if (!parsed || !parsed.projectMeta || !parsed.requirements) {
      return INITIAL_AERIS_DATA;
    }
    return parsed as AerisProjectData;
  } catch (err) {
    console.warn('Failed to load AERIS project data from localStorage, falling back to defaults:', err);
    return INITIAL_AERIS_DATA;
  }
}

export function saveProjectData(data: AerisProjectData): void {
  try {
    data.lastUpdated = new Date().toISOString();
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
  } catch (err) {
    console.error('Failed to save AERIS project data to localStorage:', err);
  }
}

export function resetProjectData(): AerisProjectData {
  const fresh = JSON.parse(JSON.stringify(INITIAL_AERIS_DATA));
  fresh.lastUpdated = new Date().toISOString();
  saveProjectData(fresh);
  return fresh;
}

export function exportProjectToJson(data: AerisProjectData): void {
  const jsonString = JSON.stringify(data, null, 2);
  const blob = new Blob([jsonString], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `AERIS1_Project_Configuration_${new Date().toISOString().split('T')[0]}.json`;
  a.click();
  URL.revokeObjectURL(url);
}

export function exportTableToCsv(filename: string, headers: string[], rows: (string | number)[][]): void {
  const escapeCsv = (val: string | number) => {
    const str = String(val);
    if (str.includes(',') || str.includes('"') || str.includes('\n')) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };

  const csvContent = [
    headers.map(escapeCsv).join(','),
    ...rows.map(row => row.map(escapeCsv).join(',')),
  ].join('\r\n');

  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename.endsWith('.csv') ? filename : `${filename}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}
